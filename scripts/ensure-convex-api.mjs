import { mkdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

// Mobile and CI import `@quipu/convex-api`, whose entry is gitignored.
// `convex-helpers ts-api-spec` needs a deployment and types missing `returns`
// validators as `any`. The checked-in `convex/_generated/api.d.ts` already
// carries the public API. Return types are inferred from each handler; a
// `returns` validator only constrains that inference. Expand that type into a
// standalone module so `tsc` does not follow Convex sources under the mobile
// compiler options.
//
// A deployment-generated spec is unnecessary: the next ensure run replaces it.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "apps/web/package.json"));
const ts = require("typescript");

const apiPath = path.join(root, "packages/convex-api/src/api.ts");
const convexDir = path.join(root, "apps/web/convex");
const configPath = path.join(convexDir, "tsconfig.json");
const generatedApiPath = path.join(convexDir, "_generated/api.d.ts");

// Alias expansion depth for TypeScript's node builder. The public
// `typeToString` keeps aliases that are not portable (`SavingsAssignPlan`,
// relative `import()`s). The builder's verbosity argument inlines them.
const ALIAS_EXPANSION_DEPTH = 20;

function fail(message) {
	console.error(message);
	process.exit(1);
}

const configFile = ts.readConfigFile(configPath, ts.sys.readFile);
if (configFile.error) {
	fail(ts.flattenDiagnosticMessageText(configFile.error.messageText, "\n"));
}

const parsed = ts.parseJsonConfigFileContent(configFile.config, ts.sys, convexDir);
const program = ts.createProgram({
	rootNames: [...parsed.fileNames, generatedApiPath],
	options: { ...parsed.options, noEmit: true },
});
const checker = program.getTypeChecker();
const source = program.getSourceFile(generatedApiPath);
if (!source) {
	fail(`Convex program did not include ${generatedApiPath}`);
}

const moduleSymbol = checker.getSymbolAtLocation(source);
if (!moduleSymbol) {
	fail(`No module symbol for ${generatedApiPath}`);
}

const apiExport = checker.getExportsOfModule(moduleSymbol).find((symbol) => symbol.name === "api");
if (!apiExport) {
	fail("convex/_generated/api.d.ts does not export `api`");
}

const apiType = checker.getTypeOfSymbolAtLocation(apiExport, source);
// `typeToTypeNode` verbosity (alias expansion) is a TypeScript-internal parameter,
// not part of the public `typeToString` signature.
const typeNode = checker.typeToTypeNode(
	apiType,
	undefined,
	ts.NodeBuilderFlags.NoTruncation,
	undefined,
	undefined,
	undefined,
	ALIAS_EXPANSION_DEPTH,
);
if (!typeNode) {
	fail("Could not print the Convex `api` type");
}

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });
const hostFile = ts.createSourceFile("api.ts", "", ts.ScriptTarget.Latest, false, ts.ScriptKind.TS);
const printed = printer.printNode(ts.EmitHint.Unspecified, typeNode, hostFile);

if (printed.includes("...") || printed.includes("import(")) {
	fail(
		"Printed Convex API type is truncated or still imports Convex source. Refusing to write api.ts.",
	);
}
if (!printed.includes("getOverview:") || !printed.includes("_returnType")) {
	fail("Printed Convex API type is missing getOverview's return slot.");
}

const contents = `import { anyApi } from "convex/server";

// Generated by scripts/ensure-convex-api.mjs from apps/web/convex/_generated/api.d.ts.
// Runtime value is anyApi. The type is the public Convex API inferred from source.
export const api = anyApi as unknown as PublicApiType;

export type PublicApiType = ${printed};
`;

mkdirSync(path.dirname(apiPath), { recursive: true });
writeFileSync(apiPath, contents);
console.log(`Wrote typed Convex API (${printed.length} chars) to ${path.relative(root, apiPath)}`);
